import React, { useState } from 'react';
import { useApp } from '../../context/AppContext';
import {
  Bell,
  CheckCircle2,
  XCircle,
  AlertTriangle,
  RotateCcw,
  CalendarCheck,
  Info
} from 'lucide-react';

export const NotificationView: React.FC = () => {
  const { notifications, clearNotifications, markNotificationsAsRead } = useApp();
  const [filterType, setFilterType] = useState<string>('all');

  const filteredNotifications = notifications.filter(n => {
    if (filterType === 'all') return true;
    const lowerTitle = n.title.toLowerCase();
    const lowerMsg = n.message.toLowerCase();

    if (filterType === 'accepted') {
      return lowerTitle.includes('accepted') || lowerTitle.includes('confirmation') || lowerTitle.includes('successful') || lowerTitle.includes('confirmed');
    }
    if (filterType === 'rejected') {
      return lowerTitle.includes('rejected') || (lowerTitle.includes('conflict') && !lowerMsg.includes('double'));
    }
    if (filterType === 'unavailable') {
      return lowerTitle.includes('unavailable') || lowerTitle.includes('occupied') || lowerMsg.includes('unavailable');
    }
    if (filterType === 'conflict') {
      return lowerTitle.includes('conflict') || lowerTitle.includes('race');
    }
    if (filterType === 'cancelled') {
      return lowerTitle.includes('cancelled') || lowerTitle.includes('cancellation');
    }
    return true;
  });

  const getNotificationIcon = (item: typeof notifications[0]) => {
    const title = item.title.toLowerCase();
    if (title.includes('cancelled') || title.includes('cancellation')) {
      return <RotateCcw className="w-5 h-5 text-amber-600" />;
    }
    if (title.includes('conflict') || title.includes('rejected') || title.includes('race')) {
      return <XCircle className="w-5 h-5 text-rose-600" />;
    }
    if (title.includes('unavailable')) {
      return <AlertTriangle className="w-5 h-5 text-amber-600" />;
    }
    if (title.includes('confirmation') || title.includes('successful') || title.includes('confirmed')) {
      return <CheckCircle2 className="w-5 h-5 text-emerald-600" />;
    }
    return <Info className="w-5 h-5 text-sky-600" />;
  };

  const getBadgeStyle = (item: typeof notifications[0]) => {
    const title = item.title.toLowerCase();
    if (title.includes('cancelled')) {
      return 'bg-amber-100 text-amber-800 border-amber-200';
    }
    if (title.includes('conflict') || title.includes('rejected') || title.includes('race')) {
      return 'bg-rose-100 text-rose-800 border-rose-200';
    }
    if (title.includes('unavailable')) {
      return 'bg-amber-100 text-amber-800 border-amber-200';
    }
    if (title.includes('confirmation') || title.includes('successful')) {
      return 'bg-emerald-100 text-emerald-800 border-emerald-200';
    }
    return 'bg-sky-100 text-sky-800 border-sky-200';
  };

  return (
    <div className="space-y-6 text-[#0b132b]">
      {/* Page Header */}
      <div className="bg-white rounded-2xl border border-sky-100 p-6 shadow-xs flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2">
            <span className="px-2.5 py-0.5 rounded-full text-[11px] font-bold uppercase tracking-wider bg-sky-100 text-sky-800 border border-sky-200">
              System Events
            </span>
            <span className="text-xs text-slate-500 font-mono">Real-time Feed</span>
          </div>
          <h1 className="text-2xl font-extrabold text-[#0b132b] mt-1.5 tracking-tight flex items-center gap-2.5">
            <Bell className="w-6 h-6 text-sky-600" />
            System Notifications
          </h1>
          <p className="text-xs text-slate-600 mt-1 max-w-2xl leading-relaxed">
            Live notification logs generated by booking events, availability checks, mutex acquisitions, and race condition conflict detections.
          </p>
        </div>

        {notifications.length > 0 && (
          <div className="flex items-center gap-2 shrink-0">
            <button
              onClick={markNotificationsAsRead}
              className="px-3.5 py-2 bg-sky-50 hover:bg-sky-100 text-sky-800 border border-sky-200 rounded-xl text-xs font-semibold transition-colors cursor-pointer"
            >
              Mark All as Read
            </button>
            <button
              onClick={clearNotifications}
              className="px-3.5 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-xl text-xs font-semibold transition-colors cursor-pointer"
            >
              Clear Log
            </button>
          </div>
        )}
      </div>

      {/* Filter Chips */}
      {notifications.length > 0 && (
        <div className="flex flex-wrap items-center gap-2">
          {[
            { id: 'all', label: 'All Notifications' },
            { id: 'accepted', label: 'Booking Accepted' },
            { id: 'rejected', label: 'Booking Rejected' },
            { id: 'unavailable', label: 'Slot Unavailable' },
            { id: 'conflict', label: 'Booking Conflict' },
            { id: 'cancelled', label: 'Reservation Cancelled' }
          ].map((tab) => (
            <button
              key={tab.id}
              onClick={() => setFilterType(tab.id)}
              className={`px-3.5 py-1.5 rounded-xl text-xs font-bold transition-all cursor-pointer ${
                filterType === tab.id
                  ? 'bg-sky-600 text-white shadow-2xs'
                  : 'bg-white border border-sky-150 text-slate-600 hover:bg-sky-50'
              }`}
            >
              {tab.label}
            </button>
          ))}
        </div>
      )}

      {/* Notifications List or Empty State */}
      {filteredNotifications.length === 0 ? (
        <div className="bg-white rounded-2xl border border-sky-100 p-16 text-center shadow-xs">
          <div className="w-14 h-14 rounded-2xl bg-sky-50 border border-sky-150 text-sky-600 flex items-center justify-center mx-auto mb-3">
            <Bell className="w-7 h-7" />
          </div>
          <h3 className="text-base font-bold text-[#0b132b]">No notifications available</h3>
          <p className="text-xs text-slate-500 max-w-sm mx-auto mt-1 leading-relaxed">
            Notifications are generated dynamically when actual bookings, cancellations, availability rejections, or mutex conflicts occur.
          </p>
        </div>
      ) : (
        <div className="space-y-3">
          {filteredNotifications.map((notif) => (
            <div
              key={notif.id}
              className={`p-4 rounded-2xl border bg-white shadow-xs transition-all flex items-start gap-3.5 ${
                notif.read ? 'border-sky-100 opacity-90' : 'border-sky-300 ring-1 ring-sky-100'
              }`}
            >
              <div className="p-2.5 rounded-xl bg-sky-50 border border-sky-100 shrink-0 mt-0.5">
                {getNotificationIcon(notif)}
              </div>

              <div className="flex-1 min-w-0">
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-1 mb-1">
                  <div className="flex items-center gap-2">
                    <span className="font-extrabold text-xs text-[#0b132b] truncate">
                      {notif.title}
                    </span>
                    <span className={`px-2 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider border ${getBadgeStyle(notif)}`}>
                      {notif.type}
                    </span>
                  </div>
                  <span className="text-[11px] font-mono text-slate-400 shrink-0">
                    {notif.timestamp}
                  </span>
                </div>

                <p className="text-xs text-slate-600 leading-relaxed">
                  {notif.message}
                </p>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
};
